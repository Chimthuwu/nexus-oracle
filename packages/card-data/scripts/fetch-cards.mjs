const RARITY = new Set(["common", "uncommon", "rare", "mythic"]);

async function fetchCard(name) {
  const url = `https://api.scryfall.com/cards/named?fuzzy=${encodeURIComponent(name)}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": USER_AGENT } });
    if (res.status === 429 || res.status >= 500) {
      await new Promise((r) => setTimeout(r, 1500 * (attempt + 1)));
      continue;
    }
    if (!res.ok) {
      throw new Error(`HTTP ${res.status} for "${name}"`);
    }
    return res.json();
  }
  throw new Error(`rate-limited for "${name}"`);
}

/** Flatten our source-of-truth fields off a raw Scryfall card JSON. */
function mapToCard(raw) {
  const faces = raw.card_faces;
  const face = faces?.[0];
  const imgs = raw.image_uris ?? face?.image_uris ?? {};
  let rarity = raw.rarity;
  if (!RARITY.has(rarity)) rarity = "rare"; // e.g. "special"/"bonus" printings
  const card = {
    id: raw.id,
    name: raw.name,
    manaCost: raw.mana_cost ?? "",
    manaValue: raw.cmc ?? 0,
    typeLine: raw.type_line ?? "",
    oracleText: (raw.oracle_text ?? face?.oracle_text ?? "").replace(/\n/g, " "),
    colors: raw.colors ?? [],
    colorIdentity: raw.color_identity ?? [],
    rarity,
    set: raw.set,
    setName: raw.set_name,
    artCropUrl: imgs.art_crop ?? "",
    imageUrl: imgs.normal ?? "",
    keywords: raw.keywords ?? [],
  };
  for (const k of ["power", "toughness", "loyalty"]) {
    if (raw[k] != null) card[k] = raw[k];
  }
  return card;
}

const ok = [];
const failed = [];
for (const name of CARD_NAMES) {
  try {
    const raw = await fetchCard(name);
    ok.push(mapToCard(raw));
    process.stdout.write(`ok   ${name}\n`);
  } catch (err) {
    failed.push(name);
    process.stdout.write(`FAIL ${name}: ${err.message}\n`);
  }
  await new Promise((r) => setTimeout(r, 450)); // stay well under Scryfall's ~10 req/s
}

if (ok.length < 30) {
  console.error(`\nOnly ${ok.length} cards fetched (need >= 30) — aborting write.`);
  process.exit(1);
}

