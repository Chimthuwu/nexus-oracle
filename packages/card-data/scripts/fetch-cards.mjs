const RARITY = new Set(["common", "uncommon", "rare", "mythic"]);

async function fetchCollection(names) {
  const url = 'https://api.scryfall.com/cards/collection';
  const identifiers = names.map(name => ({ name }));
  
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(url, {
      method: 'POST',
      headers: {
        'User-Agent': USER_AGENT,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({ identifiers })
    });
    
    if (res.status === 429 || res.status >= 500) {
      await new Promise((r) => setTimeout(r, 2000 * (attempt + 1)));
      continue;
    }
    if (!res.ok) {
      throw new Error(`HTTP ${res.status} for collection`);
    }
    return res.json();
  }
  throw new Error('rate-limited for collection');
}

/** Flatten our source-of-truth fields off a raw Scryfall card JSON. */
function mapToCard(raw) {
  const faces = raw.card_faces;
  const face = faces?.[0];
  const imgs = raw.image_uris ?? face?.image_uris ?? {};
  let rarity = raw.rarity;
  if (!RARITY.has(rarity)) rarity = "rare"; // e.g. "special"/"bonus" printings
  const card = {
    id: raw.id,
    name: raw.name,
    manaCost: raw.mana_cost ?? "",
    manaValue: raw.cmc ?? 0,
    typeLine: raw.type_line ?? "",
    oracleText: (raw.oracle_text ?? face?.oracle_text ?? "").replace(/\n/g, " "),
    colors: raw.colors ?? [],
    colorIdentity: raw.color_identity ?? [],
    rarity,
    set: raw.set,
    setName: raw.set_name,
    artCropUrl: imgs.art_crop ?? "",
    imageUrl: imgs.normal ?? "",
    keywords: raw.keywords ?? [],
  };
  for (const k of ["power", "toughness", "loyalty"]) {
    if (raw[k] != null) card[k] = raw[k];
  }
  return card;
}

